const ERGONOMIA = `# Ergonomía y bipedestación — Manual de evaluación y control

Los trastornos musculoesqueléticos son una de las principales causas de ausentismo. Este manual integra la Norma Básica de Ergonomía (R.M. 375-2008-TR) y la Ley 32721, que desde 2026 garantiza el descanso sentado a quienes trabajan de pie de forma prolongada.

## 1. Marco normativo

| Tema | Norma |
|---|---|
| Norma básica de ergonomía | R.M. 375-2008-TR |
| Descanso sentado y alternancia postural | Ley 32721, arts. 2 a 7 |
| Teletrabajo | Ley 31572, D.S. 002-2023-TR y D.S. 009-2026-TR |
| Registro de monitoreo disergonómico | D.S. 005-2012-TR, art. 33 |

## 2. Factores a evaluar

- Manipulación manual de cargas (peso, frecuencia, distancia, postura).
- Posturas forzadas y mantenidas.
- Movimientos repetitivos.
- Trabajo de pie prolongado.
- Puestos con pantallas de visualización.
- Condiciones ambientales (iluminación, temperatura).
- Organización del trabajo (pausas, ritmo, turnos).

## 3. Ley 32721 paso a paso

1. **Identifique los puestos:** donde se trabaja de pie tres horas continuas o más.
2. **Clasifique la bipedestación:** estática (sin moverse), dinámica (con desplazamientos) o prolongada (más de tres horas continuas).
3. **Revise las excepciones:** postura de pie inherente al puesto o riesgo objetivo al sentarse. Si aplica, garantice pausas activas, rotación o descansos equivalentes.
4. **Defina las sillas:** con respaldo y condiciones ergonómicas mínimas. Puede usar un sistema rotativo si las sillas alcanzan para alternar y la rotación está documentada.
5. **Organice la alternancia:** los descansos sentados forman parte de la jornada.
6. **Incorpore todo al RISST:** con aprobación del comité; plazo máximo de 360 días calendario desde la vigencia de la ley.
7. **Verifique:** con el comité o supervisor y el servicio de SST, y deje acta.

## 4. Controles recomendados

| Factor | Control |
|---|---|
| Cargas | Ayudas mecánicas, reducción del peso unitario, manipulación en equipo |
| Posturas | Rediseño de la altura de trabajo, herramientas adecuadas |
| Repetitividad | Rotación de tareas, pausas activas, automatización |
| De pie prolongado | Sillas o apoyos, tapetes antifatiga, alternancia |
| Pantallas | Monitor a la altura de los ojos, silla regulable, pausas visuales |

## 5. Errores frecuentes

- Evaluar solo oficinas y olvidar almacenes y atención al público.
- Entregar fajas lumbares como único control.
- Sillas compradas, pero sin tiempo asignado para usarlas.
- No reevaluar después de aplicar los controles.
`


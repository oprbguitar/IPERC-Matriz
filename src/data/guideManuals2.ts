const SUNAFIL = `# Prepararse para una inspección de SUNAFIL — Manual práctico

Una inspección no se gana el día de la visita: se gana con meses de gestión documentada. Este manual explica cómo se desarrolla una actuación inspectiva, qué suelen pedir, cómo se calculan las multas y cómo presentar descargos con orden.

## 1. Marco normativo

| Tema | Norma |
|---|---|
| Sistema de inspección | Ley 28806, Ley General de Inspección del Trabajo |
| Infracciones de SST y tabla de multas | D.S. 019-2006-TR (RLGIT), arts. 26 a 28 y 48 |
| Tabla vigente de multas | D.S. 008-2020-TR |
| Responsabilidad de la empresa principal | Ley 29783, art. 103 |
| Tope REMYPE | RLGIT, art. 48.1-D: 1 % de los ingresos netos del ejercicio anterior |

## 2. Cómo se desarrolla la inspección

1. **Orden de inspección:** por denuncia, accidente, operativo o de oficio.
2. **Visita o requerimiento:** el inspector puede ingresar sin previo aviso, entrevistar trabajadores y pedir documentos.
3. **Comparecencia:** la empresa presenta la documentación en la fecha indicada.
4. **Medida de requerimiento:** plazo para corregir los incumplimientos.
5. **Acta de infracción:** si no se subsana, se propone la multa.
6. **Procedimiento sancionador:** descargos, resolución de primera instancia y apelación.

## 3. Qué suelen pedir en SST

- Política, IPERC, mapa de riesgos, programa anual y RISST.
- Actas de elección e instalación del comité o del supervisor, y libro de actas.
- Los ocho registros obligatorios.
- Exámenes médicos vigentes (aptitudes).
- Registro de capacitaciones (mínimo cuatro al año).
- Entrega de EPP y verificación de su uso.
- SCTR de trabajadores en actividades de riesgo.
- En accidentes: notificación, investigación y medidas correctivas.

## 4. Gravedad y cálculo de multas

| Gravedad | Ejemplos (RLGIT) |
|---|---|
| Leve | Faltas de orden y limpieza sin riesgo grave; falta de comunicación de documentos de menor relevancia |
| Grave | No llevar registros, no evaluar riesgos, no capacitar, no realizar exámenes médicos |
| Muy grave | Incumplimientos que causan accidentes con daño grave, trabajo de menores en actividades peligrosas, no paralizar ante riesgo inminente |

La multa depende de la gravedad, del número de trabajadores afectados y del tamaño de la empresa. Hay reglas especiales: en algunos tipos se cuenta a todos los trabajadores de la empresa y en el SCTR se imputa una infracción por trabajador. La calculadora de contingencias de la plataforma aplica estas reglas e indica su grado de certeza.

## 5. Cómo responder

- Designe a una persona que acompañe al inspector y lleve un registro de lo solicitado.
- Entregue solo lo pedido, ordenado y foliado.
- Si no tiene un documento, no lo improvise: reconozca la brecha y presente el plan para cerrarla.
- Subsane dentro del plazo de la medida de requerimiento: reduce o evita la sanción.

## 6. Estructura de un descargo

1. Datos del expediente y de la empresa.
2. Hechos imputados, uno por uno.
3. Respuesta a cada hecho con la evidencia correspondiente (anexo numerado).
4. Fundamento jurídico.
5. Petitorio.

## 7. Errores frecuentes

- Presentar documentos fechados después de la visita como si fueran anteriores.
- No acreditar la inscripción en el REMYPE a tiempo.
- Contestar en bloque sin separar cada imputación.
- Ignorar la medida de requerimiento.
`

